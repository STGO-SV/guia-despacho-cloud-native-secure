CREATE TABLE GUIA_PROCESADA_RABBIT (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EVENTO_ID VARCHAR2(36 CHAR) NOT NULL,
    GUIA_ID NUMBER NOT NULL,
    TIPO_EVENTO VARCHAR2(40 CHAR) NOT NULL,
    NUMERO_GUIA VARCHAR2(80 CHAR) NOT NULL,
    TRANSPORTISTA VARCHAR2(160 CHAR) NOT NULL,
    FECHA_GUIA DATE NOT NULL,
    DESTINATARIO VARCHAR2(160 CHAR) NOT NULL,
    DIRECCION_DESTINO VARCHAR2(300 CHAR) NOT NULL,
    DESCRIPCION_CARGA VARCHAR2(1000 CHAR) NOT NULL,
    ESTADO VARCHAR2(40 CHAR) NOT NULL,
    S3_KEY VARCHAR2(500 CHAR),
    FECHA_EVENTO TIMESTAMP WITH TIME ZONE NOT NULL,
    FECHA_PROCESAMIENTO TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT UK_GUIA_PROC_EVENTO UNIQUE (EVENTO_ID)
);

CREATE INDEX IX_GUIA_PROC_GUIA_ID ON GUIA_PROCESADA_RABBIT (GUIA_ID);
